// Writes docs/i18n/ro-review.md: every Romanian string still marked
// 'machine-draft' in src/review-status.ts, next to its English source, so a
// native speaker can review a namespace in one sitting. After the review, fix
// the strings in src/catalog/ro/ and flip the namespace to 'owner-reviewed'.
//   pnpm --filter @chefer/i18n review-sheet
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { catalogs } from '../src/catalog';
import { roReviewStatus } from '../src/review-status';
import type { Namespace } from '../src/types';

type Row = { key: string; en: string; ro: string };

function flatten(en: unknown, ro: unknown, prefix: string): Row[] {
  if (typeof en === 'string') return [{ key: prefix, en, ro: String(ro) }];
  const enObj = en as Record<string, unknown>;
  const roObj = (ro ?? {}) as Record<string, unknown>;
  if ('other' in enObj) {
    // Plural: one row per Romanian form, with the closest English form.
    return Object.keys(roObj).map((form) => ({
      key: `${prefix} (${form})`,
      en: String(enObj[form] ?? enObj['other']),
      ro: String(roObj[form]),
    }));
  }
  return Object.keys(enObj).flatMap((k) => flatten(enObj[k], roObj[k], `${prefix}.${k}`));
}

const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

const drafts = (Object.keys(roReviewStatus) as Namespace[]).filter(
  (ns) => roReviewStatus[ns] === 'machine-draft',
);

const lines = [
  '# Romanian copy: owner review',
  '',
  '<!-- Generated by `pnpm --filter @chefer/i18n review-sheet`. Do not edit by hand. -->',
  '',
  'Every Romanian string an agent drafted and nobody has reviewed yet, next to its English source.',
  'Tone: "tu", warm but correct, no colloquial elisions; ș and ț with a comma below; „…” quotes.',
  '',
  'How to review: correct the string in `packages/i18n/src/catalog/ro/<namespace>.ts` (or ask an agent to),',
  "then set the namespace to `'owner-reviewed'` in `packages/i18n/src/review-status.ts` and regenerate this file.",
  '',
  ...drafts.map((ns) => `- [ ] \`${ns}\``),
  '',
];

for (const ns of drafts) {
  const rows = flatten(catalogs.en[ns], catalogs.ro[ns], ns);
  lines.push(
    `## \`${ns}\` (${rows.length} strings)`,
    '',
    '| Key | English | Română |',
    '| --- | --- | --- |',
  );
  for (const row of rows) lines.push(`| \`${row.key}\` | ${cell(row.en)} | ${cell(row.ro)} |`);
  lines.push('');
}

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../../../docs/i18n/ro-review.md');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out} (${drafts.length} namespaces)`);
